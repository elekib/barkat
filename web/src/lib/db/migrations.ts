/** The allowed bill statuses as an SQL list, for the CHECK constraints below. */
const BILL_STATUS = `(${BILL_STATUSES.map((s) => `'${s}'`).join(",")})`;

export interface Migration {
  version: number;
  sql: string;
  /** Data conversion that needs code. Runs in the same transaction, after the SQL. */
  after?: (db: Db) => void;
}

/**
 * v5: balances carry from month to month. The latest month up to today keeps its typed balances;
 * each account's opening (its first month) is set so the carry lands on them. See anchorSpace.
 */
function toLedger(db: Db): void {
  const today = new Date();
  const ym = `${today.getFullYear()}-${String(today.getMonth() + 1).padStart(2, "0")}`;
  const spaces = db.prepare("SELECT id FROM spaces").all() as { id: number }[];
  for (const sp of spaces) anchorSpace(db, sp.id, ym);
}

